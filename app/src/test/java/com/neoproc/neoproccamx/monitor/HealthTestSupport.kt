    sampleElapsedMs: Long = 10_000L,
    cameraOpen: Boolean = true,
    frameDeliveryExpected: Boolean = true,
    recording: Boolean = true,
    paused: Boolean = false,
    hardwareWarning: String? = null,
    cameraErrorMessage: String? = null,
    gpuRecordErrorMessage: String? = null,
    lastFrameDeliveryElapsedMs: Long? = 9_950L,
    previewFps: Float = 30f,
    dropEstimate: Int = 0,
    vulkanSupported: Boolean = true,
    vulkanPipelineHealthy: Boolean = true,
    consecutiveFailedImports: Long = 0L,
    sessionImportedFrames: Long = 120L,
    encoderSurfaceBound: Boolean = true,
    encoderActive: Boolean = true,
    recordingTransportLabel: String? = "P010",
    activeFeedPath: String? = "BYTEBUFFER_P010_ENCODER",
    simulatedTenBitFallbackActive: Boolean = false,
    p010SourceBitDepth: Int? = 10,
    encoderSurfaceBitDepth: Int? = null,
    encoderSurfacePrecisionProven: Boolean = false,
    encoderSurfacePrecisionFallback: Boolean = false,
    encoderOutputTenBit: Boolean? = true,
    deviceTenBitHdrSupported: Boolean = true,
    encoderP010Supported: Boolean = true,
    previewTenBitProfileApplied: Boolean = false,
    previewTransferCharacteristics: String? = "HDR10",
    computeAverageMs: Double? = 8.0,
    computeDispatched: Boolean = true,
    computeTotalDispatches: Long? = 100L,
    computePeakMs: Double? = 12.0,
    computeGpuTimestamped: Boolean = true,
    capabilitySummary: String = "nativeP010Compute=active-dispatched avgComputeMs=8.0 totalDispatches=100 gpuTimestampSamples=100",
    ispVerdictLabel: String = "PROVEN",
    ispReadbackWarning: String? = null,
    halResultsFlowing: Boolean = true,
    ispRawRequestActive: Boolean = false,
    rawStreamActive: Boolean = false,
    ispBypassSupportedByHardware: Boolean? = null,
    vendorIspPresent: Boolean? = null,
    nativeBayerActive: Boolean = false,
    capabilityBadge: String? = "Pro Cinema 83/100",
    capabilityScore: Int? = 83,
    capabilityLimitations: List<String> = emptyList(),
    lastFrameSensorTimestampNs: Long? = 5_000_000_000L,
    lastSuccessfulImportElapsedMs: Long? = 9_940L,
    sessionFailedImports: Long? = 0L,
    memoryUsageMb: Int? = 420,
    memoryUtilizationPercent: Int? = 38,
    pendingMuxerSamples: Int? = 2,
    droppedMuxerSamples: Int? = 0
): RuntimeSignalSnapshot = RuntimeSignalSnapshot(
    sampleElapsedMs = sampleElapsedMs,
    cameraOpen = cameraOpen,
    frameDeliveryExpected = frameDeliveryExpected,
    recording = recording,
    paused = paused,
    hardwareWarning = hardwareWarning,
    cameraErrorMessage = cameraErrorMessage,
    gpuRecordErrorMessage = gpuRecordErrorMessage,
    lastFrameDeliveryElapsedMs = lastFrameDeliveryElapsedMs,
    previewFps = previewFps,
    dropEstimate = dropEstimate,
    vulkanSupported = vulkanSupported,
    vulkanPipelineHealthy = vulkanPipelineHealthy,
    consecutiveFailedImports = consecutiveFailedImports,
    sessionImportedFrames = sessionImportedFrames,
    encoderSurfaceBound = encoderSurfaceBound,
    encoderActive = encoderActive,
    recordingTransportLabel = recordingTransportLabel,
    activeFeedPath = activeFeedPath,
    simulatedTenBitFallbackActive = simulatedTenBitFallbackActive,
    p010SourceBitDepth = p010SourceBitDepth,
    encoderSurfaceBitDepth = encoderSurfaceBitDepth,
