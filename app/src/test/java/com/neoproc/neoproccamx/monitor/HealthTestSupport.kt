/**
 * A neutral, non-recording preview snapshot on a 10-bit-capable device: P010 is READY (armed, not
 * recording), the ISP verification is not engaged on a processed pipeline (READY), and the GPU compute
 * pipeline is armed but idle (READY) while the pipeline liveness itself is ACTIVE (frames flowing).
 */
fun previewSnapshot(): RuntimeSignalSnapshot = healthySnapshot(
    recording = false,
    recordingTransportLabel = null,
    activeFeedPath = null,
    encoderActive = false,
    encoderSurfaceBound = false,
    p010SourceBitDepth = null,
    previewTenBitProfileApplied = false,
    computeAverageMs = null,
    computeDispatched = false,
    computeTotalDispatches = null,
    computePeakMs = null,
    ispVerdictLabel = "NOT_APPLICABLE",
    pendingMuxerSamples = null,
    droppedMuxerSamples = null
)
