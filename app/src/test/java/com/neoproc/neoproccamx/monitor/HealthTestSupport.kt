package com.neoproc.neoproccamx.monitor

/**
 * Test factory for a fully-healthy, actively-recording snapshot. Individual tests `.copy(...)` one field
 * to perturb a single signal and assert the resulting verdict, keeping each case isolated. Every new
 * [RuntimeSignalSnapshot] field is threaded through here with a sensible "healthy device" default so the
 * whole monitor suite keeps compiling.
 */
